import { randomBytes } from "node:crypto";
import { type NextRequest, NextResponse } from "next/server";

export function proxy(request: NextRequest) {
  const flag = process.env.HTTPS_DEPLOYMENT ?? "false";
  if (flag !== "true" && flag !== "false") {
    throw new Error("HTTPS_DEPLOYMENT must be true or false");
  }
  const httpsDeployment = flag === "true";
  const requestHeaders = new Headers(request.headers);

  if (
    request.nextUrl.pathname === "/api" ||
    request.nextUrl.pathname.startsWith("/api/")
  ) {
    // Next does not expose an authenticated socket peer here. Never relay viewer-
    // supplied forwarding metadata as verified client identity to a trusted backend.
    for (const name of [...requestHeaders.keys()]) {
      if (
        name === "forwarded" ||
        name.startsWith("x-forwarded-") ||
        name === "x-real-ip"
      ) {
        requestHeaders.delete(name);
      }
    }
    // This flag is an ingress contract, not proof of TLS. Direct Next access must
    // be blocked in deployments; local HTTP retains the http scheme.
    requestHeaders.set("x-forwarded-proto", httpsDeployment ? "https" : "http");
    requestHeaders.delete("x-nonce");
    requestHeaders.delete("Content-Security-Policy");
    const response = NextResponse.next({
      request: { headers: requestHeaders },
    });
    // A JSON-only fallback also covers rewrite failures generated by Next itself.
    response.headers.set(
      "Content-Security-Policy",
      "default-src 'none'; frame-ancestors 'none'; base-uri 'none'; form-action 'none'",
    );
    if (httpsDeployment)
      response.headers.set("Strict-Transport-Security", "max-age=31536000");
    return response;
  }

  const nonce = randomBytes(32).toString("base64");
  const development = process.env.NODE_ENV === "development";
  const policy = [
    "default-src 'self'",
    `script-src 'self' 'nonce-${nonce}' 'strict-dynamic'${development ? " 'unsafe-eval'" : ""}`,
    `style-src 'self' 'nonce-${nonce}'`,
    // Next's built-in error/404 components emit style attributes. Keep this
    // exception scoped to attributes; script and style elements still need nonces.
    "style-src-attr 'unsafe-inline'",
    "img-src 'self' data:",
    "font-src 'self'",
    `connect-src 'self'${development ? " ws: wss:" : ""}`,
    "object-src 'none'",
    "frame-src 'none'",
    "base-uri 'none'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    ...(httpsDeployment ? ["upgrade-insecure-requests"] : []),
  ].join("; ");
  // Replace inbound policy/nonce headers; they must never choose the rendered nonce.
  requestHeaders.set("x-nonce", nonce);
  requestHeaders.set("Content-Security-Policy", policy);
  const response = NextResponse.next({ request: { headers: requestHeaders } });
  response.headers.set("Content-Security-Policy", policy);
  response.headers.set("Cache-Control", "private, no-store");
  if (httpsDeployment) {
    response.headers.set("Strict-Transport-Security", "max-age=31536000");
  }
  return response;
}

export const config = {
  matcher: ["/((?!_next/static|_next/image|favicon.ico).*)"],
};
